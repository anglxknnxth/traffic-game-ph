// downstream.rate: vehicles per second each exit lane can discharge to the next (off-map) junction.
// downstream.exits: per-exit overrides; gateAt places that exit's discharge point (metres from the
// intersection centre) so a slow exit backs up visibly toward the box.
// demandScale multiplies every level's demand (more cars everywhere).
